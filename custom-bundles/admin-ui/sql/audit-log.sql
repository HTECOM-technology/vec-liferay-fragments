CREATE TABLE IF NOT EXISTS VEC_AUDIT_LOG (
  auditLogId BIGINT NOT NULL,
  companyId BIGINT NULL DEFAULT 0,
  groupId BIGINT NULL DEFAULT 0,
  siteName VARCHAR(255) NULL,
  userId BIGINT NULL DEFAULT 0,
  userName VARCHAR(255) NULL,
  userEmail VARCHAR(255) NULL,
  actionType VARCHAR(50) NULL,
  targetType VARCHAR(100) NULL,
  className VARCHAR(255) NULL,
  classPK VARCHAR(255) NULL,
  targetTitle VARCHAR(500) NULL,
  targetUrl VARCHAR(1000) NULL,
  beforeData LONGTEXT NULL,
  afterData LONGTEXT NULL,
  diffData LONGTEXT NULL,
  requestUri VARCHAR(1000) NULL,
  ipAddress VARCHAR(100) NULL,
  userAgent VARCHAR(1000) NULL,
  sessionId VARCHAR(255) NULL,
  status VARCHAR(50) NULL,
  errorMessage LONGTEXT NULL,
  createDate DATETIME(6) NULL,
  completedDate DATETIME(6) NULL,
  PRIMARY KEY (auditLogId),
  KEY IX_VEC_AUDIT_LOG_DATE (createDate),
  KEY IX_VEC_AUDIT_LOG_USER (userId),
  KEY IX_VEC_AUDIT_LOG_TARGET (targetType, classPK),
  KEY IX_VEC_AUDIT_LOG_ACTION (actionType),
  KEY IX_VEC_AUDIT_LOG_GROUP (groupId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
